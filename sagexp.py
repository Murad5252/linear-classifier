import numpy as np


def func(x):
    return 0.1 * x ** 2 - np.sin(x) + 5.


coord_x = np.arange(-5.0, 5.0, 0.1)
coord_y = func(coord_x)

sz = len(coord_x)
eta = np.array([0.1, 0.01, 0.001, 0.0001])
w = np.array([0., 0., 0., 0.])
N_epochs = 200
S = np.vstack([np.ones(sz), coord_x, coord_x ** 2, coord_x ** 3]).T

# --- ИНИЦИАЛИЗАЦИЯ ДЛЯ SAG ---
# Таблица памяти: хранит градиенты для каждой из 100 точек (100 строк, 4 признака)
G = np.zeros((sz, 4))

# Вектор для хранения текущего среднего градиента
g_avg = np.zeros(4)

# Цикл по эпохам
for epoch in range(N_epochs):

    # В алгоритмах стохастического спуска одна эпоха — это sz (100) случайных шагов,
    # чтобы по объему вычислений это было равно одному проходу по всем данным
    for _ in range(sz):
        # 1. Выбираем случайную точку из датасета
        i = np.random.randint(0, sz)

        x_i = S[i]  # Признаки случайной точки (4 числа)
        y_i = coord_y[i]  # Истинный ответ для этой точки

        # 2. Считаем предсказание и ошибку ТОЛЬКО для этой точки
        a_i = x_i @ w
        error_i = a_i - y_i

        # 3. Считаем градиент для этой конкретной точки
        # (без деления на sz, так как мы усредним его на следующем шаге)
        g_new = 2 * error_i * x_i

        # 4. Обновляем средний градиент (магия алгоритма SAG)
        # Вычитаем из среднего старый градиент этой точки и прибавляем новый
        g_avg = g_avg - (G[i] / sz) + (g_new / sz)

        # 5. Сохраняем новый градиент в таблицу памяти на место старого
        G[i] = g_new

        # 6. Делаем шаг: обновляем веса, используя СРЕДНИЙ градиент
        w = w - eta * g_avg

# Оценка результата (как в оригинале)
a = S @ w
Q = np.sum((a - coord_y) ** 2) / sz
w = list(w)

print("Финальные веса:", w)
print("MSE ошибка (Q):", Q)